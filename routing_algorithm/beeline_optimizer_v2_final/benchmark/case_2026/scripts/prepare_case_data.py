#!/usr/bin/env python3
"""Prepare normalized demo instances/rosters from the supplied case files.

Only fields explicitly present in the case synthetic CSV are treated as source data.
Missing operational fields are generated by dispatch.beeline_benchmark_v3 and are marked
in Instance.metadata['generated_fields']/['assumptions'].
"""
from __future__ import annotations
import argparse, json, re
from dataclasses import asdict
from pathlib import Path
from dispatch.beeline_benchmark_v3 import available_regions, from_case_region


def slug(text: str) -> str:
    mapping={'Восток':'east','Юго-восток':'south_east','Югоцентр':'south_centre'}
    if text in mapping: return mapping[text]
    return re.sub(r'[^a-z0-9]+','_',text.casefold()).strip('_') or 'region'


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--case-root', required=True)
    ap.add_argument('--out', default='reports/reproduced/prepared')
    ap.add_argument('--seed', type=int, default=42)
    args=ap.parse_args()
    out=Path(args.out); out.mkdir(parents=True, exist_ok=True)
    index=[]
    for region in available_regions(args.case_root):
        ins=from_case_region(args.case_root, region, args.seed)
        d=out/slug(region); d.mkdir(parents=True, exist_ok=True)
        ins.save(d/'instance.json')
        (d/'engineers.json').write_text(json.dumps([asdict(e) for e in ins.engineers],ensure_ascii=False,indent=2),encoding='utf8')
        (d/'requests.json').write_text(json.dumps([asdict(t) for t in ins.tasks],ensure_ascii=False,indent=2),encoding='utf8')
        meta={'region':region,'seed':args.seed,'tasks':len(ins.tasks),'engineers':len(ins.engineers),**ins.metadata}
        (d/'metadata.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2),encoding='utf8')
        index.append({'region':region,'folder':d.name,'tasks':len(ins.tasks),'engineers':len(ins.engineers)})
    (out/'index.json').write_text(json.dumps(index,ensure_ascii=False,indent=2),encoding='utf8')
    print(json.dumps(index,ensure_ascii=False,indent=2))

if __name__=='__main__': main()
